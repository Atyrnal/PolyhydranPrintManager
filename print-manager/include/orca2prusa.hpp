#pragma once
#include <fstream>
#include <string>
#include <unordered_map>

// Rewrites an OrcaSlicer .gcode into the layout libbgcode's converter expects.
// Returns an empty string on success, otherwise an error message.
inline std::string orcaToPrusaLayout(const std::string &src, const std::string &dst)
{
    auto trim = [](std::string s) {
        const auto b = s.find_first_not_of(" \t\r");
        const auto e = s.find_last_not_of(" \t\r");
        return b == std::string::npos ? std::string() : s.substr(b, e - b + 1);
    };

    // Pass 1: collect Orca config values ("; key = value" inside CONFIG_BLOCK)
    std::unordered_map<std::string, std::string> cfg;
    {
        std::ifstream in(src);
        if (!in) return "Cannot open " + src;
        std::string line;
        bool inConfig = false;
        while (std::getline(in, line)) {
            if (line.rfind("; CONFIG_BLOCK_START", 0) == 0) { inConfig = true; continue; }
            if (line.rfind("; CONFIG_BLOCK_END", 0) == 0) break;
            if (!inConfig) continue;
            const auto eq = line.find('=');
            if (line.rfind("; ", 0) != 0 || eq == std::string::npos) continue;
            cfg[trim(line.substr(2, eq - 2))] = trim(line.substr(eq + 1));
        }
        if (cfg.empty()) return "No OrcaSlicer CONFIG_BLOCK found";
    }
    auto get = [&](const std::string &k) -> std::string {
        auto it = cfg.find(k);
        if (it == cfg.end()) return {};
        std::string v = it->second;                     // multi-extruder values are comma lists
        const auto c = v.find(',');
        return trim(c == std::string::npos ? v : v.substr(0, c));
    };

    // PrusaSlicer-named print metadata. libbgcode matches keys by prefix and keeps the
    // first value it sees, so these lines must come before Orca's own config block.
    static const std::unordered_map<std::string, std::string> bedKeys = {
        {"Cool Plate", "cool_plate_temp"}, {"Engineering Plate", "eng_plate_temp"},
        {"High Temp Plate", "hot_plate_temp"}, {"Textured PEI Plate", "textured_plate_temp"},
        {"Textured Cool Plate", "textured_cool_plate_temp"}, {"Supertack Plate", "supertack_plate_temp"}};
    std::string injected;
    auto add = [&](const std::string &k, const std::string &v) {
        if (!v.empty()) injected += "; " + k + " = " + v + "\n";
    };
    add("temperature", get("nozzle_temperature"));
    if (auto it = bedKeys.find(get("curr_bed_type")); it != bedKeys.end())
        add("bed_temperature", get(it->second));
    add("fill_density", get("sparse_infill_density"));
    add("support_material", get("enable_support"));
    if (!get("ironing_type").empty())
        add("ironing", get("ironing_type") == "no ironing" ? "0" : "1");

    // Pass 2: write the rewritten file
    std::ifstream in(src);
    std::ofstream out(dst, std::ios::binary);
    if (!out) return "Cannot create " + dst;
    std::string line;
    bool producerDone = false;
    while (std::getline(in, line)) {
        if (!producerDone) {
            const auto p = line.find("generated by OrcaSlicer");
            if (p != std::string::npos) {
                std::string rest = line.substr(p + 23);  // " 2.5.0-dev on 2026-..."
                out << "; generated by PrusaSlicer" << rest << "\n";
                const std::string ver = trim(rest.substr(0, rest.find(" on ")));
                out << "; prepared by OrcaSlicer " << ver << "\n" << injected;
                producerDone = true;
                continue;
            }
        }
        if (line.rfind("; CONFIG_BLOCK_START", 0) == 0) { out << "; prusaslicer_config = begin\n"; continue; }
        if (line.rfind("; CONFIG_BLOCK_END", 0) == 0)   { out << "; prusaslicer_config = end\n";   continue; }
        out << line << "\n";
    }
    if (!producerDone) return "No 'generated by OrcaSlicer' header line";
    return out.good() ? std::string() : "Write error on " + dst;
}